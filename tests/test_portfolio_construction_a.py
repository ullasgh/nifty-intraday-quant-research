def test_o4_inverse_vol_zero_sigma_uses_floor_not_inf():
    """RED at HEAD: This catches inverse-volatility weighting that divides by a zero sigma
    without applying sigma_risk's measured floor first."""
    from nifty_quant.backtest.weighting import WEIGHT_SCHEME_REGISTRY

    signal = np.array([1.0, -0.5, 0.8, -1.2, 0.6], dtype=np.float64)
    sigma = np.array([0.0, 0.20, 0.30, 0.15, 0.40], dtype=np.float64)
    tradable = np.ones(signal.shape, dtype=bool)

    weights = WEIGHT_SCHEME_REGISTRY["inverse_vol"](signal, sigma, 0.0, tradable)
    weights = np.asarray(weights, dtype=np.float64)
    assert np.all(np.isfinite(weights))

    expected_raw = 1.0 / sigma_risk(sigma)
    normalized_weights = weights / np.sum(np.abs(weights))
    normalized_expected = expected_raw / np.sum(np.abs(expected_raw))
    np.testing.assert_allclose(
        normalized_weights, normalized_expected, rtol=1e-12, atol=1e-12
    )

    # Contrast: the naive, unfloored division WOULD have produced inf at index 0 -- this
    # is what makes the floor's necessity explicit rather than merely asserted by prose.
    with np.errstate(divide="ignore"):
        assert not np.isfinite(1.0 / sigma[0])


