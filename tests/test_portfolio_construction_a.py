def test_o9_effective_n_trials_across_schemes_is_measured_below_seven():
    """RED at HEAD: this catches a scheme comparison that scores all seven schemes as if
    independent (n_eff ~ 7) despite the genuine shared structure the spec names
    (inverse_vol/z_over_vol share a denominator, rank_weight/z_weight share an ordering),
    and separately catches a comparison that never registers its trials against a
    ResearchContract at all."""
    from nifty_quant.backtest.weighting import WEIGHT_SCHEME_REGISTRY

    n_names = 5
    n_days = 30
    # Plain, non-cherry-picked seed (rule 9: never tune a seed to make a statistical
    # assertion pass).
    rng = np.random.default_rng(0)

    scheme_names = tuple(sorted(WEIGHT_SCHEME_REGISTRY))
    assert len(scheme_names) == 7

    base_sigma = np.linspace(0.15, 0.40, n_names, dtype=np.float64)
    day_index = np.arange(n_days, dtype=np.float64)
    day_scale = 1.0 + 0.08 * np.sin(day_index / 5.0)
    sigma_noise = 0.01 * rng.standard_normal((n_days, n_names))
    sigma = (day_scale[:, None] * base_sigma[None, :] + sigma_noise).astype(np.float64)

    latent_signal = rng.standard_normal(n_days).astype(np.float64)
    signal_noise = rng.standard_normal((n_days, n_names)).astype(np.float64)
    signal = (latent_signal[:, None] + 0.15 * signal_noise).astype(np.float64)

    common_forward = rng.standard_normal(n_days).astype(np.float64)
    return_loadings = np.linspace(0.9, 1.1, n_names, dtype=np.float64)
    forward_noise = rng.standard_normal((n_days, n_names)).astype(np.float64)
    forward_return = (
        0.01 * common_forward[:, None] * return_loadings[None, :]
        + 0.002 * signal_noise
        + 0.002 * forward_noise
    ).astype(np.float64)

    tradable = np.ones(n_names, dtype=bool)
    trial_returns = np.empty((n_days, len(scheme_names)), dtype=np.float64)
    for day in range(n_days):
        for scheme_index, name in enumerate(scheme_names):
            # Causal: day d's weights use ONLY day d's own signal/sigma, never day d's or
            # any later day's forward return.
            weights = np.asarray(
                WEIGHT_SCHEME_REGISTRY[name](
                    signal[day], sigma[day], corr=0.1, tradable=tradable
                ),
                dtype=np.float64,
            )
            trial_returns[day, scheme_index] = float(weights @ forward_return[day])

    n_trials_eff = effective_n_trials(trial_returns)
    assert np.isfinite(n_trials_eff)
    assert n_trials_eff > 1.0
    assert n_trials_eff < 7.0  # 7 is a structural count of schemes, not a tuned threshold.

    contract = minimal_contract(
        validation={"scheme": "test", "holdout_intent": "never", "n_planned_trials": 7}
    )
    for expected, _name in enumerate(scheme_names, start=1):
        assert contract.register_trial() == expected

    with pytest.raises(ValueError):
        contract.register_trial()


def test_o10_promotion_uses_recent_window_not_pooled():
    """RED at HEAD: this catches a promotion decision that reads the pooled deflated
    Sharpe instead of (or in addition to) the recent-window figure -- exactly the H2
    pooled-vs-recent regression the spec cites.

    MIGRATED by the lead per AMENDMENT 5 (2026-08-31): this suite's original guess
    (`portfolio_sweep.evaluate_scheme_promotion(pooled, recent, threshold) -> bool`) lost
    the A3.5 adjudication to the returns-based interface, which is strictly stronger --
    a caller cannot hand it a pooled number relabelled as recent. Fixture, seed, and the
    pooled-passes/recent-fails self-checks are unchanged.

    AMENDMENT 6: the original self-checks (pooled > 0, recent <= 0) assumed signed-Sharpe
    semantics; deflated_sharpe is a CDF in [0, 1], so they were impossible and had never
    run (the import used to fail first). Early mean raised 0.004 -> 0.006 so the pooled
    window CLEARS the repo's actual 0.95 DSR bar (measured 0.9893) while the recent window
    fails it (0.0044); deterministic under the fixed seed."""
    from nifty_quant.research.feature_sweep import DEFLATED_SHARPE_THRESHOLD_DEFAULT
    from nifty_quant.research.portfolio_comparison import evaluate_scheme_promotion

    rng = np.random.default_rng(1)
    early_returns = rng.normal(0.006, 0.01, 48).astype(np.float64)
    recent_returns = rng.normal(-0.006, 0.01, 12).astype(np.float64)
    whole_series = np.concatenate((early_returns, recent_returns)).astype(np.float64)

    deflated_sharpe_pooled = deflated_sharpe(whole_series, sr0=0.0)
    deflated_sharpe_recent = deflated_sharpe(whole_series[-12:], sr0=0.0)

    # Intermediate facts asserted explicitly so this fails loudly, with a clear message, if
    # the fixture itself stops producing the intended pooled-passes/recent-fails contrast.
    assert deflated_sharpe_pooled > DEFLATED_SHARPE_THRESHOLD_DEFAULT
    assert deflated_sharpe_recent < DEFLATED_SHARPE_THRESHOLD_DEFAULT

    day_offsets = np.arange(0, whole_series.shape[0] + 1, 1, dtype=np.int64)
    result = evaluate_scheme_promotion(
        returns=whole_series, day_offsets=day_offsets, recent_n_sessions=12
    )
    assert result.promoted is False


