def test_o1_each_scheme_weights_sum_to_declared_gross():
    """RED at HEAD: This catches any registered weighting scheme that fails to normalize
    its unclipped output to the declared gross of 1.0."""
    from nifty_quant.backtest.weighting import WEIGHT_SCHEME_REGISTRY, apply_weight_scheme

    signal = np.array([2.0, -1.5, 0.5, -0.2, 1.0, -0.8], dtype=np.float64)
    sigma = np.array([0.15, 0.30, 0.20, 0.45, 0.10, 0.25], dtype=np.float64)
    tradable = np.ones(signal.shape, dtype=bool)

    for name in WEIGHT_SCHEME_REGISTRY:
        result = apply_weight_scheme(
            name,
            signal=signal,
            sigma=sigma,
            corr=0.2,
            tradable=tradable,
            gross=1.0,
            max_weight=1.0,
        )
        weights = np.asarray(result.weights, dtype=np.float64)
        assert np.sum(np.abs(weights)) == pytest.approx(1.0)


def test_o2_clip_binds_and_is_reported():
    """RED at HEAD: This catches inverse-volatility clipping that either allows a weight
    above max_weight or reports a constant clip_binding flag regardless of whether the
    clip actually moved anything."""
    from nifty_quant.backtest.weighting import apply_weight_scheme

    signal = np.array([1.0, -0.8, 0.6, -1.1, 0.9, -0.7], dtype=np.float64)
    sigma = np.array([0.02, 0.30, 0.25, 0.28, 0.20, 0.35], dtype=np.float64)
    tradable = np.ones(signal.shape, dtype=bool)

    clipped = apply_weight_scheme(
        "inverse_vol",
        signal=signal,
        sigma=sigma,
        corr=0.2,
        tradable=tradable,
        gross=1.0,
        max_weight=0.15,
    )
    clipped_weights = np.asarray(clipped.weights, dtype=np.float64)
    assert np.all(np.abs(clipped_weights) <= 0.15 + 1e-9)
    assert clipped.clip_binding is True

    unclipped = apply_weight_scheme(
        "inverse_vol",
        signal=signal,
        sigma=sigma,
        corr=0.2,
        tradable=tradable,
        gross=1.0,
        max_weight=1.0,
    )
    assert unclipped.clip_binding is False


